-- Baseline schema. These tables existed before Flyway was introduced
-- (created by Hibernate ddl-auto), captured here so fresh databases get
-- the same schema and Flyway owns all future changes.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    group_name  VARCHAR(255),
    role        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE courses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    code        VARCHAR(255) NOT NULL,
    instructor  VARCHAR(255),
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_courses_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE pages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT NOT NULL,
    course_id   BIGINT,
    parent_id   BIGINT,
    title       VARCHAR(255) NOT NULL,
    icon        VARCHAR(16),
    cover_style VARCHAR(32),
    content     JSONB,
    search_text TEXT,
    favorite    BOOLEAN NOT NULL,
    position    DOUBLE PRECISION NOT NULL,
    archived_at TIMESTAMP(6),
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_pages_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_pages_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE SET NULL,
    CONSTRAINT fk_pages_parent FOREIGN KEY (parent_id) REFERENCES pages (id) ON DELETE SET NULL
);

CREATE INDEX idx_courses_user ON courses (user_id);
CREATE INDEX idx_pages_owner ON pages (owner_id);
CREATE INDEX idx_pages_parent ON pages (parent_id);
