-- Minimal assignment drafts for workspace search. Scheduling is added in F1.
CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP(6) NOT NULL,
    search_title TEXT NOT NULL DEFAULT '',
    search_vector TSVECTOR NOT NULL DEFAULT ''::tsvector
);
CREATE INDEX idx_assignments_owner ON assignments(owner_id);

CREATE FUNCTION deadlinr_update_assignment_search() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.search_title := lower(unaccent(NEW.title));
    NEW.search_vector := setweight(to_tsvector('simple', unaccent(NEW.title)), 'A')
                      || setweight(to_tsvector('simple', unaccent(NEW.description)), 'B');
    RETURN NEW;
END;
$$;
CREATE TRIGGER assignments_search_update
BEFORE INSERT OR UPDATE OF title, description ON assignments
FOR EACH ROW EXECUTE FUNCTION deadlinr_update_assignment_search();
CREATE INDEX idx_assignments_search_vector ON assignments USING gin(search_vector);
CREATE INDEX idx_assignments_search_title ON assignments USING gin(search_title gin_trgm_ops);
