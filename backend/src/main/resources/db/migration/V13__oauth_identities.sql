ALTER TABLE users ADD COLUMN password_login_enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(16) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_oauth_provider CHECK (provider IN ('google', 'github')),
    CONSTRAINT ck_oauth_subject CHECK (LENGTH(TRIM(subject)) > 0),
    CONSTRAINT fk_oauth_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_oauth_subject UNIQUE (provider, subject),
    CONSTRAINT uk_oauth_user_provider UNIQUE (user_id, provider)
);
