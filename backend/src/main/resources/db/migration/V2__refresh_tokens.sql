-- Refresh tokens (opaque, rotating) for short-lived-access-JWT auth.
-- auth_epoch on users lets "log out everywhere" invalidate all access
-- tokens instantly: the access JWT carries the epoch, the filter compares
-- it with the current value on the user row.

CREATE TABLE refresh_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL,
    token_hash     VARCHAR(64) NOT NULL,
    family_id      UUID NOT NULL,
    expires_at     TIMESTAMP(6) NOT NULL,
    created_at     TIMESTAMP(6) NOT NULL,
    revoked_at     TIMESTAMP(6),
    replaced_by_id BIGINT,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_replaced FOREIGN KEY (replaced_by_id) REFERENCES refresh_tokens (id) ON DELETE SET NULL
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);

ALTER TABLE users ADD COLUMN auth_epoch BIGINT NOT NULL DEFAULT 0;
